import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
const source = new URL('dist/commonroom/', root);
const read = (file) => readFile(new URL(file, source), 'utf8');
const asScript = (module) => module
  .replace(/^import \{[^\n]+\} from '\.\/[^'\n]+';\r?\n/gm, '')
  .replace(/^export /gm, '');
const version = (content) => createHash('sha256').update(content.replace(/\r\n/g, '\n')).digest('hex').slice(0, 12);

const [html, client, ui, threads, app, store, style, threadStyle] = await Promise.all(
  ['index.html', 'client.js', 'ui.js', 'threads.js', 'app.js', 'preview-store.js', 'style.css', 'threads.css'].map(read),
);
const preferencesStart = client.indexOf('export function loadSaved(');
if (preferencesStart < 0) throw new Error('Commonroom preferences could not be located.');

const script = [store, 'const request = previewRequest;', client.slice(preferencesStart), ui, threads, app]
  .map(asScript).join('\n\n');
const bundle = '// Generated by npm run build:preview.\n(async () => {\n"use strict";\n' + script + '\n})();\n';
const preview = html
  .replace('<html lang="en">', '<html lang="en" data-local-preview data-theme="dark">')
  .replace('<title>Commonroom</title>', '<title>Commonroom preview</title>')
  .replace('href="/commonroom/style.css"', 'href="./dist/commonroom/style.css?v=' + version(style) + '"')
  .replace('href="/commonroom/threads.css"', 'href="./dist/commonroom/threads.css?v=' + version(threadStyle) + '"')
  .replace('<script type="module" src="/commonroom/app.js"></script>', '<script defer src="./commonroom-preview.js?v=' + version(bundle) + '"></script>')
  .replace('<small>BIC student space</small>', '<small>Posts stay in this browser</small>')
  .replace('<small>Guest identity</small>', '<small>Local guest</small>')
  .replace('<body>', '<body>\n  <noscript>Enable JavaScript to try the Commonroom preview.</noscript>');

await Promise.all([
  writeFile(new URL('commonroom.html', root), '<!-- Generated by npm run build:preview. -->\n' + preview),
  writeFile(new URL('commonroom-preview.js', root), bundle),
]);
